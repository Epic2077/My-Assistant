import { env } from "../env.ts";
import { Store } from "../store.ts";
import type { InboundMessage } from "../types.ts";
import type { MessageHandler, OutboundPort } from "../handler.ts";

// Loaded by require() only when explicitly enabled so the core project does not
// install Puppeteer or an unofficial WhatsApp client unless the user opts in.
export class WhatsAppConnector implements OutboundPort {
  private client: any;
  private readonly pendingBotReplies = new Set<string>();
  private readonly store: Store;
  private readonly handler: MessageHandler;
  private readonly onStatus: (status: string) => void;

  constructor(store: Store, handler: MessageHandler, onStatus: (status: string) => void) {
    this.store = store;
    this.handler = handler;
    this.onStatus = onStatus;
  }

  async start(): Promise<void> {
    if (!env.whatsappEnabled) return;
    if (!/^(127\.0\.0\.1|localhost|::1)$/.test(env.host)) throw new Error("For safety, the dashboard must bind to localhost before enabling WhatsApp.");

    let library: any;
    let qrTerminal: any;
    try {
      const whatsappPackage = "whatsapp-web.ts";
      const qrPackage = "qrcode-terminal";
      library = await import(whatsappPackage);
      qrTerminal = await import(qrPackage);
    } catch {
      throw new Error("WhatsApp integration is enabled but optional packages are missing. Run: npm install whatsapp-web.js qrcode-terminal");
    }

    const Client = library.Client || library.default?.Client;
    const LocalAuth = library.LocalAuth || library.default?.LocalAuth;
    const generate = qrTerminal.generate || qrTerminal.default?.generate;
    if (!Client || !LocalAuth) throw new Error("Could not load whatsapp-web.js exports.");

    this.onStatus("starting browser session");
    this.client = new Client({
      authStrategy: new LocalAuth({ clientId: "personal-gatekeeper" }),
      puppeteer: { headless: true, args: ["--no-sandbox", "--disable-setuid-sandbox"] },
    });
    this.client.on("qr", (qr: string) => {
      this.onStatus("scan QR code");
      console.log("\n[WhatsApp] Scan this QR code using WhatsApp → Linked devices. Your account risk is non-zero because this connector is unofficial.\n");
      if (typeof generate === "function") generate(qr, { small: true });
      else console.log(qr);
    });
    this.client.on("authenticated", () => this.onStatus("authenticated"));
    this.client.on("ready", () => {
      this.onStatus("connected · unofficial WhatsApp Web session");
      this.store.addEvent({ kind: "connector", platform: "whatsapp", details: "WhatsApp Web session is ready. This is an unofficial connector." });
      console.log("[WhatsApp] Connected. Group chats and status messages are ignored.");
    });
    this.client.on("auth_failure", (message: string) => {
      this.onStatus("authentication failed");
      this.store.addEvent({ kind: "error", platform: "whatsapp", details: `WhatsApp authentication failed: ${message}` });
    });
    this.client.on("disconnected", (reason: string) => {
      this.onStatus(`disconnected · ${reason}`);
      this.store.addEvent({ kind: "connector", platform: "whatsapp", details: `WhatsApp disconnected: ${reason}` });
    });
    this.client.on("message_create", (msg: any) => {
      try {
        if (!msg.fromMe || !msg.to || msg.to.endsWith("@g.us") || msg.to === "status@broadcast") return;
        const body = String(msg.body || msg.caption || "").trim();
        const echoKey = `${msg.to}:${body}`;
        // Ignore the echo generated by this assistant's own sendMessage call.
        if (this.pendingBotReplies.has(echoKey)) {
          this.pendingBotReplies.delete(echoKey);
          return;
        }
        const at = new Date(Number(msg.timestamp || Math.floor(Date.now() / 1000)) * 1000).toISOString();
        this.handler.observeOwnerMessage("whatsapp", `whatsapp:${msg.to}`, body, at, String(msg.id?._serialized || msg.id?.id || ""));
      } catch (error) {
        const detail = error instanceof Error ? error.message : String(error);
        this.store.addEvent({ kind: "error", platform: "whatsapp", details: `Could not record manual outgoing WhatsApp message: ${detail}` });
      }
    });

    this.client.on("message", async (msg: any) => {
      try {
        if (msg.fromMe || msg.isStatus || !msg.from || msg.from.endsWith("@g.us") || msg.from === "status@broadcast") return;
        const contact = await msg.getContact().catch(() => null);
        const senderName = contact?.pushname || contact?.name || contact?.shortName || msg.from;
        const body = String(msg.body || msg.caption || "").trim();
        const inbound: InboundMessage = {
          platform: "whatsapp",
          id: String(msg.id?._serialized || msg.id?.id || `${msg.from}:${msg.timestamp}`),
          chatId: String(msg.from),
          contactKey: `whatsapp:${msg.from}`,
          senderName: String(senderName),
          text: body || "[The contact sent a non-text message. Ask what they need; do not infer unseen attachment content.]",
          timestamp: new Date(Number(msg.timestamp || Math.floor(Date.now() / 1000)) * 1000).toISOString(),
        };
        await this.handler.handle(inbound);
      } catch (error) {
        const detail = error instanceof Error ? error.message : String(error);
        console.error(`[WhatsApp] Incoming message handler failed: ${detail}`);
        this.store.addEvent({ kind: "error", platform: "whatsapp", details: `Incoming message handler failed: ${detail}` });
      }
    });
    await this.client.initialize();
  }

  async send(message: InboundMessage, text: string): Promise<void> {
    if (!this.client) throw new Error("WhatsApp client is not initialized.");
    const echoKey = `${message.chatId}:${text}`;
    this.pendingBotReplies.add(echoKey);
    setTimeout(() => this.pendingBotReplies.delete(echoKey), 10_000).unref?.();
    await this.client.sendMessage(message.chatId, text);
  }

  async stop(): Promise<void> {
    if (this.client) await this.client.destroy().catch(() => undefined);
    this.onStatus("stopped");
  }
}
